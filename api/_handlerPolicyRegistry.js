export function buildHandlerPolicyRegistry(moduleAccess, authExemptHandlers = new Set()) {
  const accessNames = Object.keys(moduleAccess || {});
  const behaviorNames = Object.keys(HANDLER_BEHAVIOR);
  const missingBehavior = accessNames.filter((name) => !HANDLER_BEHAVIOR[name]);
  const orphanBehavior = behaviorNames.filter((name) => !Object.prototype.hasOwnProperty.call(moduleAccess, name));
  if (missingBehavior.length || orphanBehavior.length) {
    throw new Error(`FCOS handler policy registry mismatch. Missing: ${missingBehavior.join(', ') || 'none'}; orphaned: ${orphanBehavior.join(', ') || 'none'}.`);
  }
  return Object.freeze(Object.fromEntries(accessNames.map((name) => [name, Object.freeze({
    ...HANDLER_BEHAVIOR[name],
    modules: Object.freeze([...(moduleAccess[name] || [])]),
    authentication: authExemptHandlers.has(name) ? 'cron' : 'active_user',
  })])));
}

export function handlerPolicyFor(registry, name) {
  return Object.prototype.hasOwnProperty.call(registry || {}, name) ? registry[name] : null;
}

export function registeredHandlerBehavior(name) {
  return Object.prototype.hasOwnProperty.call(HANDLER_BEHAVIOR, name) ? HANDLER_BEHAVIOR[name] : null;
}

export function registeredHandlerCapabilities() {
  return [...new Set(Object.values(HANDLER_BEHAVIOR).map((entry) => entry.capability).filter(Boolean))];
}

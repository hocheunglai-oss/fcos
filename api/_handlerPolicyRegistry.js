function policy({ mutation, cache = 'none', externalAction = false, capability = null }) {
  return Object.freeze({
    mutation,
    cache,
    externalAction,
    capability,
    audit: mutation || externalAction ? 'required' : 'none',
  });
}

function readPolicy(options = {}) {
  return policy({ ...options, mutation: false });
}

function mutationPolicy(options = {}) {
  return policy({ ...options, mutation: true });
}


import * as documents from '../src/lib/pageMethodologies.js';
import * as userManuals from '../src/lib/pageUserManuals.js';
import { PAGE_METHODOLOGIES } from '../src/hedge/lib/methodology.js';
import { XERO_PORTAL_MANUALS } from '../src/lib/xeroPortalManual.js';
import { mkdir, writeFile } from 'node:fs/promises';

// Preserve one editable source; browsers load long-form help only on demand.
const contents = {};
let index = "// Generated by scripts/write-methodology-assets.mjs; edit pageMethodologies.js.\nconst contentUrl = new URL('../content/page-methodologies.json', import.meta.url).href;\n";
const descriptor = (document, key) => {
  contents[key] = document;
  return { title: document.title, description: document.description, contentKey: key };
};
for (const [name, value] of Object.entries(documents)) {
  const summary = value.title ? descriptor(value, name) : Object.fromEntries(Object.entries(value).map(([key, document]) => [key, descriptor(document, `${name}:${key}`)]));
  index += `\nexport const ${name} = ${JSON.stringify(summary, null, 2).replaceAll('"contentKey":', 'contentUrl, "contentKey":')};\n`;
}
const hedgeTitles = Object.keys(PAGE_METHODOLOGIES);
for (const [title, methodology] of Object.entries(PAGE_METHODOLOGIES)) {
  contents[`hedge:${title}`] = {
    sections: [
      { title: 'Purpose', body: methodology.summary },
      { title: 'Calculation and control rules', points: methodology.steps },
    ],
    sources: methodology.sources || [],
  };
}
index += `\nexport const HEDGE_METHODOLOGY_TITLES = ${JSON.stringify(hedgeTitles)};\n`;
index += 'export const HEDGE_METHODOLOGY_URL = contentUrl;\n';

await mkdir(new URL('../src/content/', import.meta.url), { recursive: true });
await writeFile(new URL('../src/content/page-methodologies.json', import.meta.url), JSON.stringify(contents));
await writeFile(new URL('../src/lib/pageMethodologyIndex.js', import.meta.url), index);

await writeFile(new URL('../src/content/xero-portal-manual.json', import.meta.url), JSON.stringify(XERO_PORTAL_MANUALS));

const manualIndex = Object.entries(userManuals).map(([key, manual]) =>
  `export const ${key} = { title: ${JSON.stringify(manual.title)}, description: ${JSON.stringify(manual.description)}, contentUrl, contentKey: ${JSON.stringify(key)} };`,
).join('\n');
await writeFile(new URL('../src/content/page-user-manuals.json', import.meta.url), JSON.stringify(userManuals));
await writeFile(new URL('../src/lib/pageUserManualIndex.js', import.meta.url),
  `// Generated by scripts/write-methodology-assets.mjs; edit pageUserManuals.js.\nconst contentUrl = new URL('../content/page-user-manuals.json', import.meta.url).href;\n\n${manualIndex}\n`);
